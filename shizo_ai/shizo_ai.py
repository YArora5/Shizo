def camera_react(emotion, message=""):
    """Send a camera-based emotion and message to SHIZO with cooldown."""
    global last_camera_emotion, last_camera_reaction_time

    now = time.time()

    if emotion == last_camera_emotion:
        if now - last_camera_reaction_time < CAMERA_REACTION_COOLDOWN:
            return

    last_camera_emotion = emotion
    last_camera_reaction_time = now

    send_emotion_to_shizo(emotion, message)

    print(f"CAMERA REACTION: {emotion}")
    if message:
        print(f"CAMERA MESSAGE: {message}")


def camera_loop():

    global camera_running



    print("Loading YOLO camera model...")



    try:

        model = YOLO("yolo11n.pt")

    except Exception as error:

        print("CAMERA ERROR: Could not load YOLO model.")

        print(error)

        camera_running = False

        return



    cap = cv2.VideoCapture(0)



    if not cap.isOpened():

        print("CAMERA ERROR: Laptop camera could not be opened.")

        camera_running = False

        return



    print("Laptop camera started.")

    print("Press Q in the camera window to close camera detection.")



    stable_object = None

    stable_since = time.time()

    last_sent_object = None



    while camera_running:

        ret, frame = cap.read()



        if not ret:

            print("CAMERA ERROR: Could not read camera frame.")

            break



        try:

            results = model(frame, verbose=False)

            result = results[0]

        except Exception as error:

            print("CAMERA DETECTION ERROR:", error)

            continue



        detected_objects = []



        if result.boxes is not None:

            for box in result.boxes:

                class_id = int(box.cls[0])

                confidence = float(box.conf[0])

                name = model.names[class_id]



                if confidence >= 0.40:

                    detected_objects.append(name)



        detected_set = set(detected_objects)



        # Priority: person > cell phone > other object > nothing
        if "person" in detected_set:
            detected_object = "person"
            emotion = "HAPPY"
            camera_message = "I SEE YOU!"
        elif "cell phone" in detected_set:
            detected_object = "cell phone"
            emotion = "CURIOUS"
            camera_message = "WHAT'S THAT?"
        elif detected_objects:
            detected_object = detected_objects[0]
            emotion = "SURPRISE"
            camera_message = "WHOA!"
        else:
            detected_object = None
            emotion = "NORMAL"
            camera_message = ""

        # Require the same detection to remain stable before reacting.

        if detected_object != stable_object:

            stable_object = detected_object

            stable_since = time.time()



        stable_for = time.time() - stable_since



        if stable_for >= CAMERA_STABLE_TIME:

            if detected_object != last_sent_object:

                if detected_object:

                    print(

                        "CAMERA DETECTED:",

                        ", ".join(sorted(detected_set))

                    )

                else:

                    print("CAMERA: Nothing detected")



                camera_react(emotion, camera_message)

                last_sent_object = detected_object



        annotated_frame = result.plot()

        cv2.imshow("SHIZO - Laptop Camera", annotated_frame)



        if cv2.waitKey(1) & 0xFF == ord("q"):

            camera_running = False

            break



    cap.release()

    cv2.destroyAllWindows()

    print("Laptop camera stopped.")





def start_camera():

    """Start camera detection without blocking SHIZO text chat."""

    camera_thread = threading.Thread(

        target=camera_loop,

        daemon=True

    )

    camera_thread.start()

    return camera_thread





